"""Embed dashboard assets: browser firmware upload needs no separate uploadfs."""
Import("env")
from pathlib import Path
import gzip
root = Path(env.subst("$PROJECT_DIR"))
output = ["// Generated by embed_web.py; do not edit.\n#pragma once\n"]
for name, symbol in [("index.html", "web_index"), ("app.js", "web_app"), ("styles.css", "web_styles")]:
    data = gzip.compress((root / "data" / name).read_bytes(), mtime=0)
    output.append(f"static const uint8_t {symbol}[] PROGMEM = {{\n")
    for i in range(0, len(data), 24):
        output.append(",".join(str(b) for b in data[i:i+24]) + ",\n")
    output.append("};\n")
build = Path(env.subst("$BUILD_DIR"))
build.mkdir(parents=True, exist_ok=True)
env.Append(CPPPATH=[str(build)])
path = build / "web_assets.h"
text = "".join(output)
if not path.exists() or path.read_text() != text:
    path.write_text(text)
